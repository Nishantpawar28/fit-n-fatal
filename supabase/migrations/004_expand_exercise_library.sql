-- Fit N Fatal - Expanded exercise library
-- Splits "Arms" into Biceps / Triceps / Forearms and adds system exercises
-- for every muscle group. Safe to re-run: existing names are skipped.

-- =========================================================================
-- Re-categorise existing system exercises
-- =========================================================================
UPDATE exercises SET muscle_group = 'Biceps'
WHERE user_id IS NULL AND muscle_group = 'Arms'
  AND name IN ('Barbell Curl', 'Dumbbell Curl', 'Hammer Curl', 'Preacher Curl');

UPDATE exercises SET muscle_group = 'Triceps'
WHERE user_id IS NULL AND muscle_group = 'Arms'
  AND name IN ('Tricep Pushdown', 'Skull Crushers', 'Overhead Tricep Extension', 'Close-Grip Bench Press');

UPDATE exercises SET secondary_muscle_group = 'Chest'
WHERE user_id IS NULL AND name = 'Close-Grip Bench Press';

UPDATE exercises SET name = 'Chest Dips', secondary_muscle_group = 'Triceps'
WHERE user_id IS NULL AND name = 'Dips';

UPDATE exercises SET secondary_muscle_group = 'Back'
WHERE user_id IS NULL AND name IN ('Conventional Deadlift', 'Sumo Deadlift', 'Romanian Deadlift');

UPDATE exercises SET exercise_type = 'cardio'
WHERE user_id IS NULL AND name IN ('Battle Ropes', 'Box Jumps');

